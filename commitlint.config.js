/** Commit trailers and lines that credit an assistant or a coding tool. */
const TOOL_CREDIT =
  /^(co-authored-by:.*(devin|claude|cursor|copilot|codex|gpt|openai|anthropic|\[bot\])|generated[- ]with\b|generated by\b)/im

export default {
  extends: ['@commitlint/config-conventional'],
  plugins: [
    {
      rules: {
        'no-tool-credit': ({ raw }) => [
          !TOOL_CREDIT.test(raw ?? ''),
          'commits are credited to their human author only: remove the Co-Authored-By / "Generated with" line',
        ],
      },
    },
  ],
  rules: { 'no-tool-credit': [2, 'always'] },
}
